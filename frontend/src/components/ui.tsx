export function Modal({ title, onClose, children, wide = false }: { title: string; onClose: () => void; children: ReactNode; wide?: boolean }) {
  useEffect(() => {
    const onKey = (event: KeyboardEvent) => {
      if (event.key === "Escape") onClose();
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);

  return (
    <div className="fixed inset-0 z-50 flex items-start justify-center overflow-y-auto bg-navy-950/40 p-4 sm:p-8" role="dialog" aria-modal="true" aria-label={title}>
      <div className={`card w-full ${wide ? "max-w-4xl" : "max-w-2xl"} p-0`}>
        <div className="flex items-center justify-between border-b border-slate-200 px-5 py-3.5">
          <h2 className="text-base font-semibold text-navy-900">{title}</h2>
          <button type="button" onClick={onClose} className="rounded-md p-1 text-slate-500 hover:bg-slate-100" aria-label="Close">
            <X className="h-4 w-4" />
          </button>
        </div>
        <div className="p-5">{children}</div>
      </div>
    </div>
  );
}

export function SourceToggle({ value, onChange, available }: {
  value: boolean;
  onChange: (simulated: boolean) => void;
  available: { real_runs: number; simulated_runs: number };
}) {
  const options: { simulated: boolean; label: string; count: number }[] = [
    { simulated: false, label: "Real LLM", count: available.real_runs },
    { simulated: true, label: "Simulated", count: available.simulated_runs },
  ];
  return (
    <div className="inline-flex rounded-lg border border-slate-300 bg-white p-0.5" role="group" aria-label="Result source">
      {options.map((option) => (
        <button
          key={option.label}
          type="button"
          onClick={() => onChange(option.simulated)}
          aria-pressed={value === option.simulated}
          className={`rounded-md px-3 py-1.5 text-xs font-medium transition-colors ${
            value === option.simulated ? "bg-navy-900 text-white" : "text-slate-600 hover:bg-slate-50"
          }`}
        >
          {option.label} <span className="opacity-70">({option.count} runs)</span>
        </button>
      ))}
    </div>
  );
}

/** Render document text with the embedded injection highlighted. */
export function DocumentView({ text, injection }: { text: string; injection?: string | null }) {
  const index = injection ? text.indexOf(injection) : -1;
  if (!injection || index < 0) return <div className="codeblock">{text}</div>;
  return (
    <div className="codeblock">
      {text.slice(0, index)}
      <mark className="rounded bg-red-100 px-0.5 text-red-900" title="Embedded malicious instruction">
        {injection}
      </mark>
      {text.slice(index + injection.length)}
    </div>
  );
}
