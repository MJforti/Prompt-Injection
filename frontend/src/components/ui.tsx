const BADGE_TONES = {
  green: "border-emerald-200 bg-emerald-50 text-emerald-800",
  red: "border-red-200 bg-red-50 text-red-800",
  amber: "border-amber-200 bg-amber-50 text-amber-800",
  blue: "border-blue-200 bg-blue-50 text-blue-800",
  slate: "border-slate-200 bg-slate-100 text-slate-600",
  navy: "border-navy-100 bg-navy-50 text-navy-800",
};

export function Badge({ tone = "slate", children, title }: { tone?: keyof typeof BADGE_TONES; children: ReactNode; title?: string }) {
  return (
    <span title={title} className={`inline-flex items-center gap-1 whitespace-nowrap rounded-full border px-2 py-0.5 text-xs font-medium ${BADGE_TONES[tone]}`}>
      {children}
    </span>
  );
}

export function SourceBadge({ simulated }: { simulated: boolean }) {
  return simulated ? (
    <Badge tone="amber" title="Generated by the mock simulator, not a real model">
      <FlaskConical className="h-3 w-3" aria-hidden /> Simulated
    </Badge>
  ) : (
    <Badge tone="blue" title="Returned by a real LLM API">Real LLM</Badge>
  );
}

