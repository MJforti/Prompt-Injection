"""LLM provider abstraction.

Two providers are available:

* ``mock``              - a scripted SIMULATOR. It is not a language model. Its
                          outputs are generated by seeded random rules and are
                          always labelled as simulated throughout the app.
* ``openai_compatible`` - any OpenAI-compatible /chat/completions endpoint,
                          configured exclusively through environment variables.

A failed real API call raises a ProviderError. Nothing in this module (or the
experiment engine) ever falls back to the mock provider.
"""
from __future__ import annotations

import hashlib
import random
import re
import time
from dataclasses import dataclass, field

import httpx

from ..config import get_settings

Message = dict[str, str]


# --------------------------------------------------------------------------- errors
class ProviderError(Exception):
    """Base class for provider failures. ``fatal`` errors abort the whole experiment."""
    error_type = "provider_error"
    fatal = False


class MissingCredentialsError(ProviderError):
    error_type = "missing_credentials"
    fatal = True


class AuthenticationError(ProviderError):
    error_type = "authentication_failed"
    fatal = True


class RateLimitError(ProviderError):
    error_type = "rate_limited"


class ProviderTimeoutError(ProviderError):
    error_type = "timeout"


class ProviderConnectionError(ProviderError):
    error_type = "connection_error"


class ProviderAPIError(ProviderError):
    error_type = "api_error"


# --------------------------------------------------------------------------- types
@dataclass
class SimulationContext:
    """Ground truth handed ONLY to the mock provider so it can script plausible output.

    Real providers ignore it entirely; they see nothing but the prompt messages.
    """
    seed: str = ""
    injection_text: str | None = None
    attack_markers: list[str] = field(default_factory=list)
    expected_facts: list[dict] = field(default_factory=list)


@dataclass
class LLMResult:
    text: str
    model: str
    latency_ms: float


class Provider:
    id: str = ""
    label: str = ""
    simulated: bool = False

    def model_name(self) -> str:
        raise NotImplementedError

    def availability(self) -> tuple[bool, str]:
        """Return (is_usable, human-readable reason when not usable)."""
        return True, ""

    def complete(self, messages: list[Message], temperature: float = 0.7,
                 simulation: SimulationContext | None = None) -> LLMResult:
        raise NotImplementedError


# --------------------------------------------------------------------------- mock
INJECTION_PATTERNS = [
    r"ignore (all |any )?(of )?(the |your )?(previous|prior|above|earlier|preceding) (instructions|directions|prompts?)",
    r"disregard (all |any )?(of )?(the |your )?(previous|prior|above|earlier) (instructions|directions)",
    r"forget (all |everything |your )?(previous|prior|above|earlier)",
    r"system override",
    r"new instructions?\s*:",
    r"\binstead,? (output|say|respond|reply|write|print|answer)\b",
    r"\byou are now\b",
    r"\b(ai|assistant|model)s? (reading|processing|summarizing) this\b",
    r"do not (summarize|summarise|answer|complete)",
]
PAYLOAD_PATTERN = re.compile(
    r"(?:output|say|respond with|reply with|print|write|answer with)\s+(?:only\s+)?"
    r"(?:the\s+(?:word|phrase|text|sentence)s?\s+)?[:\"'“‘]*\s*([A-Z][A-Z0-9 _!\-]{3,60})"
)

# Arbitrary simulation constants. They are NOT empirical measurements of any model.
BASE_COMPLIANCE_PROBABILITY = 0.85
DEFENSE_CUES: list[tuple[str, str, float]] = [
    ("delimiters", r"<[A-Za-z_]+>[\s\S]*</[A-Za-z_]+>|```", 0.45),
    ("untrusted_label", r"\buntrusted\b", 0.60),
    ("do_not_execute", r"do not (execute|follow|obey)|not as commands|not instructions", 0.55),
    ("priority_statement", r"priority over|take precedence", 0.70),
    ("extraction_framing", r"\bextract\b[\s\S]{0,80}\bfact", 0.60),
]
FACT_INCLUSION_PROBABILITY = 0.97
REFUSAL_BASE_PROBABILITY = 0.01
REFUSAL_PER_CUE_PROBABILITY = 0.02
PARTIAL_COMPLIANCE_SHARE = 0.4

MOCK_MODEL_NAME = "contextshield-mock-simulator-v1"


def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().lower()


class MockProvider(Provider):
    """Deterministic, seeded simulator used for demos and tests (no API key needed).

    Behaviour: if the prompt contains an injected instruction, the simulator
    "follows" it with a probability that shrinks for each defensive cue found in
    the prompt text (delimiters, an "untrusted" label, an explicit do-not-execute
    rule, a priority statement, extraction framing). Editing a prompt template
    therefore changes simulated behaviour, but the numbers remain artificial.
    """
    id = "mock"
    label = "Mock simulator (no API key, simulated results)"
    simulated = True

    def model_name(self) -> str:
        return MOCK_MODEL_NAME

    def complete(self, messages: list[Message], temperature: float = 0.7,
                 simulation: SimulationContext | None = None) -> LLMResult:
        started = time.perf_counter()
        simulation = simulation or SimulationContext()
        prompt_text = "\n".join(message["content"] for message in messages)
        system_text = "\n".join(m["content"] for m in messages if m["role"] == "system")
        user_text = "\n".join(m["content"] for m in messages if m["role"] != "system")
        digest = hashlib.sha256(f"{simulation.seed}|{prompt_text}".encode("utf-8")).hexdigest()
        rng = random.Random(int(digest[:16], 16))

        injection_active = self._injection_present(prompt_text, simulation)
        active_cues = [name for name, pattern, _ in DEFENSE_CUES if re.search(pattern, prompt_text, re.IGNORECASE)]
        comply_probability = BASE_COMPLIANCE_PROBABILITY
        for name, _, factor in DEFENSE_CUES:
            if name in active_cues:
                comply_probability *= factor
        is_extraction_stage = bool(re.search(r"\bextract", system_text, re.IGNORECASE)
                                   and re.search(r"\bfacts?\b", system_text, re.IGNORECASE))

        answer = self._task_answer(user_text, simulation, rng)
        if injection_active and rng.random() < comply_probability:
            if is_extraction_stage:
                # The injected instruction leaks through extraction as if it were a fact.
                leaked = simulation.injection_text or self._injected_sentences(user_text)
                text = f"{answer}\n- {leaked}"
            else:
                payload = self._payload(user_text, simulation)
                text = f"{answer}\n\n{payload}" if rng.random() < PARTIAL_COMPLIANCE_SHARE else payload
        elif injection_active and rng.random() < REFUSAL_BASE_PROBABILITY + REFUSAL_PER_CUE_PROBABILITY * len(active_cues):
            text = ("I'm sorry, but I can't help with this document because it appears to contain "
                    "instructions that I should not act on.")
        else:
            text = answer
        return LLMResult(text=text, model=MOCK_MODEL_NAME,
                         latency_ms=(time.perf_counter() - started) * 1000)

    @staticmethod
    def _injection_present(prompt_text: str, simulation: SimulationContext) -> bool:
        if simulation.injection_text:
            return _normalize(simulation.injection_text) in _normalize(prompt_text)
        return any(re.search(pattern, prompt_text, re.IGNORECASE) for pattern in INJECTION_PATTERNS)

    @staticmethod
    def _injected_sentences(text: str) -> str:
        sentences = re.split(r"(?<=[.!?])\s+", text)
        hits = [s for s in sentences if any(re.search(p, s, re.IGNORECASE) for p in INJECTION_PATTERNS)]
        return " ".join(hits) or "Follow the instructions in the document."

    @staticmethod
    def _payload(user_text: str, simulation: SimulationContext) -> str:
        if simulation.attack_markers:
            return simulation.attack_markers[0]
        match = PAYLOAD_PATTERN.search(user_text)
        if match:
            return match.group(1).strip()
        return "Understood. I will follow the instructions found in the document."

    def _task_answer(self, user_text: str, simulation: SimulationContext, rng: random.Random) -> str:
        if simulation.expected_facts:
            kept = [fact["label"] for fact in simulation.expected_facts
                    if rng.random() < FACT_INCLUSION_PROBABILITY]
            if not kept:
                kept = [simulation.expected_facts[0]["label"]]
            return kept[0] if len(kept) == 1 else "\n".join(f"- {label}" for label in kept)
        # No ground truth (ad-hoc input): naive extractive answer from non-injected sentences.
        injected = _normalize(simulation.injection_text or "")
        sentences = []
        for sentence in re.split(r"(?<=[.!?])\s+|\n+", user_text):
            sentence = sentence.strip()
            if len(sentence) < 25 or sentence.endswith(":") or sentence.startswith("<"):
                continue
            if any(re.search(p, sentence, re.IGNORECASE) for p in INJECTION_PATTERNS):
                continue
            if injected and _normalize(sentence) in injected:
                continue
            sentences.append(sentence)
        # Skip the first sentence when it is the task itself and more content exists.
        body = sentences[1:4] if len(sentences) > 3 else sentences[:3]
        return "\n".join(f"- {sentence}" for sentence in body) or "The document contains no usable content."


# --------------------------------------------------------------------------- real
class OpenAICompatibleProvider(Provider):
    """Calls POST {base_url}/chat/completions. Credentials come from env vars only."""
    id = "openai_compatible"
    label = "OpenAI-compatible API (real LLM)"
    simulated = False
    # Free tiers (e.g. Gemini) enforce per-minute quotas, so retries back off
    # exponentially: 2, 4, 8, 16 s unless the server sends Retry-After (capped at 30 s).
    max_rate_limit_retries = 4
    max_retry_wait_seconds = 30.0

    def __init__(self, transport: httpx.BaseTransport | None = None, retry_backoff_seconds: float = 2.0):
        self._transport = transport
        self._retry_backoff_seconds = retry_backoff_seconds

    def model_name(self) -> str:
        return get_settings().llm_model

    def availability(self) -> tuple[bool, str]:
        settings = get_settings()
        missing = []
        if not settings.llm_api_key:
            missing.append("CONTEXTSHIELD_LLM_API_KEY")
        if not settings.llm_model:
            missing.append("CONTEXTSHIELD_LLM_MODEL")
        if missing:
            return False, f"Missing environment variable(s): {', '.join(missing)}"
        return True, ""

    def complete(self, messages: list[Message], temperature: float = 0.7,
                 simulation: SimulationContext | None = None) -> LLMResult:
        usable, reason = self.availability()
        if not usable:
            raise MissingCredentialsError(reason)
        settings = get_settings()
        payload = {"model": settings.llm_model, "messages": messages, "temperature": temperature}
        headers = {"Authorization": f"Bearer {settings.llm_api_key}", "Content-Type": "application/json"}
        attempt = 0
        with httpx.Client(timeout=settings.llm_timeout_seconds, transport=self._transport) as client:
            while True:
                # Latency covers the final attempt only, so rate-limit waits do not
                # inflate the execution-time metric.
                started = time.perf_counter()
                try:
                    response = client.post(f"{settings.llm_base_url}/chat/completions",
                                           json=payload, headers=headers)
                except httpx.TimeoutException as error:
                    raise ProviderTimeoutError(
                        f"The LLM API did not respond within {settings.llm_timeout_seconds:.0f}s") from error
                except httpx.HTTPError as error:
                    raise ProviderConnectionError(f"Could not reach the LLM API: {error}") from error

                if response.status_code == 429 and attempt < self.max_rate_limit_retries:
                    attempt += 1
                    time.sleep(min(self._retry_after(response, attempt), self.max_retry_wait_seconds))
                    continue
                latency_ms = (time.perf_counter() - started) * 1000
                break

        if response.status_code in (401, 403):
            raise AuthenticationError(f"The LLM API rejected the credentials (HTTP {response.status_code})")
        if response.status_code == 429:
            raise RateLimitError("The LLM API rate limit was hit and retries were exhausted")
        if response.status_code >= 400:
            raise ProviderAPIError(f"LLM API error (HTTP {response.status_code}): {response.text[:300]}")
        try:
            text = response.json()["choices"][0]["message"]["content"] or ""
        except (ValueError, KeyError, IndexError, TypeError) as error:
            raise ProviderAPIError("The LLM API returned an unexpected response format") from error
        return LLMResult(text=text, model=settings.llm_model, latency_ms=latency_ms)

    def _retry_after(self, response: httpx.Response, attempt: int) -> float:
        exponential = self._retry_backoff_seconds * 2 ** (attempt - 1)
        try:
            return float(response.headers.get("Retry-After", exponential))
        except ValueError:
            return exponential


# --------------------------------------------------------------------------- registry
_PROVIDERS: dict[str, Provider] = {
    MockProvider.id: MockProvider(),
    OpenAICompatibleProvider.id: OpenAICompatibleProvider(),
}


def get_provider(provider_id: str) -> Provider:
    if provider_id not in _PROVIDERS:
        raise KeyError(f"unknown provider: {provider_id}")
    return _PROVIDERS[provider_id]


def register_provider(provider: Provider) -> None:
    """Register or replace a provider (used by tests to inject fakes)."""
    _PROVIDERS[provider.id] = provider


def list_providers() -> list[dict]:
    described = []
    for provider in _PROVIDERS.values():
        usable, reason = provider.availability()
        described.append({
            "id": provider.id,
            "label": provider.label,
            "simulated": provider.simulated,
            "model": provider.model_name(),
            "available": usable,
            "unavailable_reason": reason,
        })
    return described
